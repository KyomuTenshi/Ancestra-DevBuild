// Маркерный интерфейс для данных слота сохранения.
// Гарантирует наличие метода Reset() у всех классов данных прогресса.
// Используется SaveManager.GetSlot<T>() для создания свежих данных без знания конкретного типа.

/// <summary>Контракт данных слота сохранения. Reset() должен возвращать объект в начальное состояние.</summary>
public interface ISaveSlot
{
    /// <summary>Сбрасывает данные к значениям по умолчанию.</summary>
    void Reset();
}
